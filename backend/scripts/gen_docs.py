"""Generate docs/API_DOCUMENTATION.md and docs/DATABASE_SCHEMA.md from the real code.

Run:  python scripts/gen_docs.py
The generated tables can never drift from the implementation because they are built from it.
"""

from __future__ import annotations

import inspect
import os
import sys
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BACKEND))
os.environ.setdefault("APP_ENV", "test")
os.environ.setdefault("JWT_SECRET", "docs-generation-only-secret-0123456789")

from fastapi.routing import APIRoute  # noqa: E402

from app.api.routes import auth, documents, misc, review  # noqa: E402
from app.db import models  # noqa: E402,F401
from app.db.base import Base  # noqa: E402

DOCS = BACKEND.parent / "docs"


def roles_of(route: APIRoute) -> str:
    def walk(dep):  # type: ignore[no-untyped-def]
        for d in dep.dependencies:
            allowed = getattr(d.call, "allowed_roles", None)
            if allowed:
                return allowed
            found = walk(d)
            if found:
                return found
            if getattr(d.call, "__name__", "") == "current_user":
                return ("any signed-in user",)
        return None

    found = walk(route.dependant)
    if not found:
        return "public"
    if found == ("any signed-in user",):
        return "any signed-in user"
    return (
        "/".join(sorted(found, key=["viewer", "reviewer", "admin"].index))
        if set(found) != {"admin", "reviewer", "viewer"}
        else "viewer and above"
    )


def api_doc() -> str:
    lines = [
        "# API documentation",
        "",
        "*Generated by `scripts/gen_docs.py` from the FastAPI routes. When the API is running, interactive documentation is at "
        "`/docs` (Swagger UI) and the machine-readable spec at `/openapi.json`.*",
        "",
        "## Conventions",
        "",
        "- Base path: `/api/v1` (health checks are at the root: `/health`, `/health/ready`).",
        "- Authentication: `Authorization: Bearer <token>` from `POST /api/v1/auth/login`. Tokens expire after `ACCESS_TOKEN_MINUTES` (default 60).",
        "- Roles: **viewer** (read-only) < **reviewer** (upload, correct, approve, reprocess, compare) < **admin** (delete, users, audit log).",
        '- Errors always look like `{"error": {"code": "...", "message": "...", "details": [...]}}`. '
        "Common codes: `unauthorized` (401), `forbidden` (403), `not_found` (404), `file_rejected` (422), `file_too_large` (413), "
        "`validation_error` (422), `rate_limited` (429, with `Retry-After`), `conflict` (409).",
        "- Lists are paginated with `page` (from 1) and `size` (max 100) and return `{items, total, page, size}`.",
        "- Uploads return `202 Accepted` immediately; processing continues in the background. Poll `GET /documents/{id}/status`.",
        "- Rate limits: 240 requests/min per user (login: 10/min per IP). Configurable.",
        "",
        "## Endpoints",
        "",
        "| Method | Path | Who | Summary |",
        "|---|---|---|---|",
    ]
    rows = []
    for router, prefix in (
        (misc.health_router, ""),
        (auth.router, "/api/v1"),
        (documents.router, "/api/v1"),
        (review.router, "/api/v1"),
        (misc.router, "/api/v1"),
    ):
        for r in router.routes:
            if isinstance(r, APIRoute):
                doc = (inspect.getdoc(r.endpoint) or r.name.replace("_", " ")).splitlines()[0]
                for m in sorted(r.methods - {"HEAD", "OPTIONS"}):
                    rows.append((r.tags[0] if r.tags else "", prefix + r.path, m, roles_of(r), doc))
    order = {"health": 0, "auth": 1, "documents": 2, "review": 3, "search": 4, "comparisons": 5, "stats": 6, "admin": 7}
    for _tag, path, method, who, doc in sorted(rows, key=lambda x: (order.get(x[0], 9), x[1], x[2])):
        lines.append(f"| {method} | `{path}` | {who} | {doc} |")
    lines += [
        "",
        "## Key request/response shapes",
        "",
        "**Upload** — `POST /api/v1/documents` (multipart, field `files`, up to `MAX_FILES_PER_REQUEST` files). Response:",
        "```json",
        '{"results": [{"filename": "a.pdf", "status": "accepted|duplicate|rejected", "document_id": "uuid|null", "reason": "..."}]}',
        "```",
        "`422` if every file was rejected, otherwise `202`.",
        "",
        "**Extraction** — `GET /api/v1/documents/{id}/extractions` returns one object per *logical document* "
        "(an invoice/receipt/other found inside the file). Each has `fields` (value, original_value, corrected, confidence, "
        "`source` = extracted|inferred|corrected, `grounded`, `page`, `bbox`, `raw_text`), `line_items`, `validation` "
        "(rule_code, severity, message, expected, actual) and `corrections`. `bbox` is `[x0,y0,x1,y1]` in page units for PDFs/images "
        "or `{sheet, cell}` for spreadsheets.",
        "",
        '**Correction** — `PATCH /api/v1/logical-documents/{id}/fields/{name}` with `{"value": "...", "reason": "..."}`. '
        "Send `null` to clear a value. Validation is re-run immediately.",
        "",
        "**Search** — `GET /api/v1/search?q=...&mode=keyword|semantic|hybrid` plus filters `supplier`, `customer`, `invoice_number`, "
        "`date_from`, `date_to`, `status`, `doc_type`, `currency`, `min_total`, `max_total`, `needs_review`. "
        "Snippets mark matches with `[[[` and `]]]` (never HTML). `GET /api/v1/invoices` lists invoices with the same filters, sorting and pagination.",
        "",
        '**Comparison** — `POST /api/v1/comparisons` with `{"left_document_id", "right_document_id"}`. Verdicts per field: '
        "`match`, `mismatch`, `uncertain`, `missing_in_left`, `missing_in_right`, `not_comparable`. Every item carries the evidence "
        "(`left_source`/`right_source`: file, page, bbox or sheet+cell) and the rule that was applied.",
        "",
        '**Reprocess** — `POST /api/v1/documents/{id}/reprocess` with `{"mode": "resume"}` (retry what failed) or '
        '`{"mode": "reextract"}` (new extraction version; manual corrections are kept). `POST /api/v1/documents/reprocess-failed` re-queues everything that failed.',
        "",
        "## Document status lifecycle",
        "",
        "`uploaded → queued → validating → processing → analyzing → completed | needs_review`, or `failed` / `rejected` "
        "(corrupted, encrypted or unsupported content). `needs_review` means at least one invoice failed validation, has low confidence, "
        "a page failed, or the file had to be repaired.",
        "",
    ]
    return "\n".join(lines)


def schema_doc() -> str:
    lines = [
        "# Database schema",
        "",
        "*The table listings below are generated by `scripts/gen_docs.py` from the SQLAlchemy models, and the Alembic migration "
        "`backend/alembic/versions/0001_initial_schema.py` is verified against them by `alembic check` (see the test-suite).*",
        "",
        "PostgreSQL 16 with the `vector` (pgvector) extension.",
        "",
        "## Design notes",
        "",
        "- **Money** is `NUMERIC(18,4)` and `Decimal` in Python. Never floats.",
        "- **Extractions are versioned.** Re-extracting creates a new `extractions` row (`is_current`); old ones stay.",
        "- **Corrections are separate rows.** The effective value of a field is the latest correction, else the current extraction. "
        "Reprocessing therefore cannot destroy a reviewer's work.",
        "- **A file can hold many invoices.** `documents` (the file) → `logical_documents` (each invoice/receipt/other, with a page range).",
        "- `logical_documents` also stores *denormalised effective values* (supplier, number, date, total, currency, review flags) for fast filtering; "
        "they are refreshed after every extraction or correction.",
        "- **Search indexes:** a GIN expression index `ix_pages_fts` on `to_tsvector('english', pages.text)` and an HNSW cosine index "
        "`ix_page_embeddings_hnsw` on `page_embeddings.embedding` (384 dimensions).",
        "- **Idempotency & recovery:** stage hand-off uses atomic `UPDATE ... WHERE status = X` claims on `documents.status`; "
        "`documents.updated_at` lets the reaper find stalled work.",
        "- Deleting a document cascades to everything derived from it.",
        "",
        "## Tables",
        "",
    ]
    for table in sorted(Base.metadata.tables.values(), key=lambda t: t.name):
        lines += [f"### `{table.name}`", "", "| Column | Type | Null | Notes |", "|---|---|---|---|"]
        for col in table.columns:
            notes = []
            if col.primary_key:
                notes.append("PK")
            if col.unique:
                notes.append("unique")
            for fk in col.foreign_keys:
                notes.append(
                    f"FK → {fk.column.table.name}" + (f" (on delete {fk.ondelete.lower()})" if fk.ondelete else "")
                )
            lines.append(
                f"| `{col.name}` | {str(col.type).split('(')[0] if 'VECTOR' not in str(col.type).upper() else 'vector(384)'}"
                f"{'(' + str(col.type).split('(', 1)[1] if '(' in str(col.type) and 'VECTOR' not in str(col.type).upper() else ''} "
                f"| {'yes' if col.nullable else 'no'} | {', '.join(notes)} |"
            )
        idx = sorted(i.name for i in table.indexes if i.name)
        uniq = [
            ", ".join(c.name for c in con.columns)
            for con in table.constraints
            if con.__class__.__name__ == "UniqueConstraint"
        ]
        if idx:
            lines += ["", "Indexes: " + ", ".join(f"`{i}`" for i in idx)]
        if uniq:
            lines += ["", "Unique constraints: " + "; ".join(f"({u})" for u in uniq)]
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    DOCS.mkdir(exist_ok=True)
    (DOCS / "API_DOCUMENTATION.md").write_text(api_doc())
    (DOCS / "DATABASE_SCHEMA.md").write_text(schema_doc())
    print("written docs/API_DOCUMENTATION.md and docs/DATABASE_SCHEMA.md")


if __name__ == "__main__":
    main()
